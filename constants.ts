// Offline template for the three perspectives. It reuses the user's own words
// and makes no claims about what the event means.
export const getFallbackData = (lang: Language, fact = '', interpretation = '') => {
    const isZh = lang === 'zh';
    return {
        reframes: {
            observer: fact || (isZh ? "只写下实际看到、听到的部分。" : "Write only what was seen or heard."),
            possibilities: isZh
              ? `“${interpretation || '这个想法'}”是一种可能。还有哪两种？`
              : `“${interpretation || 'This story'}” is one possibility. What are two others?`,
            agency: isZh
              ? "选一个你能掌控的小动作：暂停、问一句，或先离开一会儿。"
              : "Pick one small move you control: pause, ask, or step away.",
        }
    };
};

